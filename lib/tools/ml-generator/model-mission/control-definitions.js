function explanation(label, shortHelp) {
  return {
    what: `${label} is a project setting.`,
    why: shortHelp,
    useWhen: "Use the recommended value first, then adjust it when your project needs a different trade-off.",
    codeEffect: "The generated Python configuration uses this value.",
  };
}

function control({
  id,
  taskIds,
  section,
  step,
  level,
  label,
  controlType,
  defaultValue,
  shortHelp,
  visibleWhen,
  enabledWhen,
}) {
  return {
    id,
    taskIds,
    section,
    step,
    level,
    label,
    controlType,
    defaultValue,
    shortHelp,
    explanation: explanation(label, shortHelp),
    ...(visibleWhen ? { visibleWhen } : {}),
    ...(enabledWhen ? { enabledWhen } : {}),
  };
}

