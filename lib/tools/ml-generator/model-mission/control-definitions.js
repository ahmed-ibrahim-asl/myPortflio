function explanation({ id, shortHelp, section, configKey }) {
  const [what, useWhen, avoidWhen, tradeoff, codeEffect] = CONTROL_EXPLANATIONS[id]
    ?? [
      `${id} is a recipe setting for this mission.`,
      `Use it when the ${id} setting needs to reflect your dataset or runtime.`,
      `Avoid changing ${id} without checking its effect on the generated workflow.`,
      `Changing ${id} can improve fit for your environment but may add runtime or complexity.`,
    ];
  return {
    what,
    why: shortHelp,
    useWhen,
    avoidWhen,
    tradeoff,
    codeEffect: codeEffect
      ?? `The generated Python ${section} configuration sets ${configKey ?? id} to the selected value.`,
  };
}

function control({
  id,
  taskIds,
  section,
  step,
  level,
  label,
  controlType,
  defaultValue,
  configKey,
  explanationId,
  shortHelp,
  visibleWhen,
  enabledWhen,
}) {
  return {
    id,
    taskIds,
    section,
    step,
    level,
    label,
    controlType,
    defaultValue,
    shortHelp,
    ...(configKey ? { configKey } : {}),
    explanation: explanation({
      id: explanationId ?? id,
      shortHelp,
      section,
      configKey,
    }),
    ...(visibleWhen ? { visibleWhen } : {}),
    ...(enabledWhen ? { enabledWhen } : {}),
  };
}

