function legacyShortHelp(taskId, fieldId) {
  if (
    ["object-detection", "instance-segmentation"].includes(taskId) &&
    YOLO_LEGACY_SHORT_HELP[fieldId]
  ) {
    return YOLO_LEGACY_SHORT_HELP[fieldId];
  }
  return `Configure ${legacyLabel(fieldId)} for this ${taskId.replaceAll("-", " ")} workflow.`;
}

function legacyLabel(fieldId) {
  return fieldId
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1 $2")
    .replace(/^./, (character) => character.toUpperCase());
}

function legacyLevel(fieldId, index) {
  return LEGACY_TRAINING_LEVELS[fieldId]
    ?? ["guided", "customize", "advanced"][index % 3];
}

